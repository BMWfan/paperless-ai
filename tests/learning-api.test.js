'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const express=require('express');
const cookieParser=require('cookie-parser');
const {openLearningStore}=require('../services/learningStore');
const {createLearningRouter,sameOriginJSON}=require('../routes/learning');
const {createManualUpdateHandler}=require('../routes/manualLearning');
const {authenticateJWT}=require('../routes/auth');

test('authenticated learning routes validate origins, expose history and obey manual mode on partial edits',async t=>{
  const directory=fs.mkdtempSync(path.join(os.tmpdir(),'learning-api-'));
  const store=openLearningStore(path.join(directory,'test.db'));
  const previous=process.env.API_KEY;process.env.API_KEY='isolated-contract-api-key';
  let current={id:1,title:'Before',tags:[7],document_type:3,correspondent:4};
  store.observe(current);store.configure({mode:'manual'});let reschedules=0;
  const paperless={async updateDocument(id,updates,options){
    assert.equal(id,1);assert.equal(options.confirmedUser,true);assert.equal(options.actor,'api-key');
    current={...current,...updates};store.observe(current,'confirmed_ui',{actor:options.actor});return current;
  },async getDocument(){return current;},async getLearningVocabulary(){return {tags:new Map([[7,'Invoice']])};}};
  const app=express();app.use(express.json(),cookieParser(),authenticateJWT);
  app.use('/api/learning',createLearningRouter({store,paperless,monitor:{reschedule(){reschedules++;},async scan(){return {scanned:1};}}}));
  app.post('/manual/updateDocument',sameOriginJSON,createManualUpdateHandler(paperless,{async addProcessedDocument(){}}));
  const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
  t.after(()=>{server.closeAllConnections();server.close();store.close();fs.rmSync(directory,{recursive:true,force:true});if(previous===undefined)delete process.env.API_KEY;else process.env.API_KEY=previous;});
  const base=`http://127.0.0.1:${server.address().port}`;
  const request=(route,body,extra={})=>fetch(base+route,{method:body===undefined?'GET':'POST',headers:{'x-api-key':'isolated-contract-api-key','Content-Type':'application/json',...extra},...(body===undefined?{}:{body:JSON.stringify(body)})});
  assert.equal((await fetch(base+'/api/learning/events')).status,401);
  const jwt=require('jsonwebtoken');
  const token=jwt.sign({id:17},process.env.JWT_SECRET || 'your-secret-key');
  assert.equal((await fetch(base+'/api/learning/events',{headers:{Cookie:`jwt=${token}`}})).status,200);
  assert.equal((await fetch(base+'/api/learning/events',{headers:{Cookie:'jwt=invalid'}})).status,403);
  assert.equal((await request('/api/learning/settings',{}, {Origin:'invalid origin'})).status,400);
  assert.equal((await request('/api/learning/settings',{}, {Origin:'https://untrusted.example'})).status,403);
  assert.equal((await request('/api/learning/settings',{enabled:false})).status,200);assert.equal(reschedules,1);
  assert.equal((await request('/api/learning/settings',{mode:'invented'})).status,400);
  assert.equal((await request('/manual/updateDocument',{documentId:1,title:'Partial correction'})).status,200);
  assert.deepEqual(current.tags,[7]);assert.equal(current.document_type,3);
  let response=await (await request('/api/learning/events?status=pending')).json();assert.equal(response.total,1);
  const event=response.events[0];assert.equal(event.source,'confirmed_ui');assert.equal(store.examples().length,0);
  assert.equal((await request(`/api/learning/events/${event.id}/review`,{decision:'confirmed'})).status,200);
  response=await (await request('/api/learning/history?documentId=1')).json();assert.equal(response.history[0].actor,'api-key');
  assert.equal((await request(`/api/learning/events/${event.id}/review`,{decision:'deleted'})).status,200);
  assert.equal(store.examples().length,0);
  assert.equal((await request('/manual/updateDocument',{documentId:1})).status,400);
  assert.equal((await request('/manual/updateDocument',{documentId:1,tags:'invalid'})).status,400);
  await request('/api/learning/settings',{mode:'disabled'});
  assert.equal((await request('/api/learning/scan',{})).status,409);
  assert.equal((await request('/manual/updateDocument',{documentId:1,title:'No learning'})).status,200);
  assert.equal(store.list().length,1);
  await request('/api/learning/settings',{mode:'manual'});
  assert.equal((await request('/manual/updateDocument',{documentId:1,correspondent:{id:9,name:'Selected synthetic correspondent'},document_type:5,custom_fields:[{field:1,value:'synthetic'}]})).status,200);
  assert.equal(current.correspondent,9);assert.equal(current.document_type,5);assert.deepEqual(current.tags,[7]);
  let candidate=store.listPending()[0];
  current={...current,title:'Changed outside the application'};
  assert.equal((await request(`/api/learning/events/${candidate.id}/review`,{decision:'confirmed'})).status,409,'fresh Paperless metadata prevents a stale approval');
  candidate=store.listPending()[0];
  const approved=await fetch(base+`/api/learning/events/${candidate.id}/review`,{method:'POST',headers:{Cookie:`jwt=${token}`,Origin:base,'Content-Type':'application/json'},body:JSON.stringify({decision:'confirmed'})});
  assert.equal(approved.status,200);
  assert.equal(store.history(1)[0].actor,'user:17');
});
